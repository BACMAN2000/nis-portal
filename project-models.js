const L = (en, es) => ({en: en, es: es});

/* w(): una semana. Se escribe posicional porque son 146 y el ruido de las
   claves repetidas hacia el archivo ilegible. */
function w(n, aliento, tipo, titulo, que, partes, apoyo, mejora){
  return {n: n, aliento: aliento,
    modelo: {tipo: tipo, titulo: titulo, que: que, partes: partes, apoyo: apoyo || [], mejora: mejora}};
}
/* f(): el producto final del arco. */
function f(tipo, titulo, que, partes, apoyo, mejora){
  return {tipo: tipo, titulo: titulo, que: que, partes: partes, apoyo: apoyo || [], mejora: mejora};
}
function arco(final, semanas){
  const s = {};
  semanas.forEach(x => { s[x.n] = x; });
  return {final: final, semanas: s};
}

