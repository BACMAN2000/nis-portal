/* Modelos de entrega de los proyectos de primaria — NIS 2026.
 *
 * QUE RESUELVE
 * Cada arco pide once o doce entregas y hasta ahora el alumno solo tenia el
 * NOMBRE de cada una ("Evidence Map", "Field Journal", "Problem tree"). Un
 * nino de siete anos no sabe que forma tiene eso. Aqui cada semana trae:
 *
 *   aliento -> una frase que nombra el logro de ESA semana, no un animo
 *              generico. Se lee al abrir la semana.
 *   modelo  -> {tipo, titulo, que, partes, apoyo, mejora}
 *              tipo   : cual de las 25 laminas de project-art.js lo dibuja
 *              titulo : como se llama la entrega
 *              que    : que es, en una frase
 *              partes : lo que tiene que llevar. Son a la vez la lista de
 *                       comprobacion y las etiquetas del dibujo, asi que van
 *                       cortas (2-4 palabras).
 *              apoyo  : frases EN INGLES que el alumno puede usar tal cual.
 *                       No se traducen: son la lengua que se esta aprendiendo.
 *              mejora : como se pasa de "hecho" a "bien hecho". Es la parte
 *                       que el usuario pidio: que el alumno vea el modelo y
 *                       pueda MEJORAR el suyo.
 *
 * Y cada arco trae `final`, el modelo del producto final con la misma forma.
 *
 * DE DONDE SALE
 * De las `fases` de project-arcs.js: cada semana de aqui responde a la
 * evidencia que ese arco ya declaraba. NO se inventan entregas nuevas ni se
 * cambia lo que el colegio escribio; se le da forma visible. Si en
 * project-arcs.js cambia una evidencia, hay que cambiar su modelo aqui: el
 * barrido de tools/audita_modelos.js avisa de las semanas sin modelo.
 *
 * BILINGUE, como project-arcs.js: L('English','castellano'). Una cadena
 * suelta es un nombre propio o un texto igual en los dos idiomas. El `apoyo`
 * va siempre en ingles a proposito.
 *
 * NIVEL DE LENGUA del apoyo: G1-G2 Starters, G3-G4 Movers, G5 Flyers, que es
 * la escalera Cambridge del colegio.
 */
